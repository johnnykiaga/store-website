QUIRE.money = function money(n) {
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 0,
  }).format(n);
};

QUIRE.byId = function byId(id) {
  return QUIRE.products.find(function (p) { return p.id === id; });
};

